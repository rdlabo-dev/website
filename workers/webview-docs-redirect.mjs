export function webviewDocsRedirect(request) {
  const url = new URL(request.url);
  const historical = historicalPaths[url.pathname.replace(/\/$/, '')];
  if (historical) {
    const destination = new URL(historical);
    destination.search = url.search;
    return Response.redirect(destination, 301);
  }
  const match = url.pathname.match(/^((?:\/(?:ja|fr|de))?)\/(?:projects\/)?([^/]+)(\/.*)?$/);
  if (!match || !WEBVIEW_PROJECT_IDS.includes(match[2])) return undefined;
  const [, locale, id, suffix = ''] = match;
  const path = `${locale}/projects/${id}${suffix}`;
  const destination = new URL(
    historicalPaths[path.replace(/\/$/, '')] ?? path,
    WEBVIEW_DOCS_ORIGIN,
  );
  destination.search = url.search;
  return Response.redirect(destination, 301);
}
